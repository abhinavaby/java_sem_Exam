package module_1;

public class loop {
    public static void main(String[] args) {
        int i = 5;
        while(i!=0){
            System.out.println(i);
            i--;

        }
        System.out.println();
        for(int j = 0 ; j<6 ; j++){
            System.out.println(j);
        }
    }
}
